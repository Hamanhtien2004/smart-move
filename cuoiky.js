/* Thông tin và popup phương tiện */
function setupServiceCards() {
    const modal = document.getElementById('serviceModal');

    document.querySelectorAll('.card').forEach((card) => {
        if (!card.dataset.vehicle && !card.dataset.title) return;

        const cardImage = card.querySelector('img');
        const vehicle = getVehicleInfo(card);

        // Nếu ảnh trong images/ chưa có, thử ảnh minh họa trực tuyến.
        if (cardImage && vehicle?.fallbackImage) {
            cardImage.addEventListener('error', () => {
                if (cardImage.dataset.fallbackUsed === 'true') {
                    cardImage.classList.add('image-missing');
                    return;
                }

                cardImage.dataset.fallbackUsed = 'true';
                cardImage.src = vehicle.fallbackImage;
            });
        }

        card.addEventListener('click', () => {
            if (!modal) return;

            const info = getVehicleInfo(card);
            if (!info) return;

            const title = document.getElementById('modalTitle');
            const shortDesc = document.getElementById('modalShortDesc');
            const longDesc = document.getElementById('modalLongDesc');

            if (title) title.textContent = info.title;
            if (shortDesc) shortDesc.textContent = info.summary;
            if (longDesc) longDesc.textContent = info.details;
            renderVehiclePhotoSpin(info);

            openModal(modal);
        });
    });

    modal?.querySelector('.close-btn')?.addEventListener('click', () => {
        closeModal('serviceModal');
    });

    modal?.addEventListener('click', (event) => {
        if (event.target === modal) closeModal('serviceModal');
    });

    modal?.querySelector('.modal-booking-link')?.addEventListener('click', () => {
        closeModal('serviceModal');
    });
}

function getVehicleInfo(card) {
    const key = (card.dataset.vehicle || '').toLowerCase();
    let info = xeSmartMove[key];

    // Tự nhận dạng dòng xe nếu thẻ chỉ có data-title.
    if (!info) {
        const titleText = (card.dataset.title || '').toLowerCase();

        if (titleText.includes('vento')) info = xeSmartMove.ventos;
        else if (titleText.includes('lạc hồng') || titleText.includes('lac hong')) {
            info = xeSmartMove.lachong;
        } else if (titleText.includes('vinbus') || titleText.includes('buýt')) {
            info = xeSmartMove.vinbus;
        }
    }

    const cardImage = card.querySelector('img');

    return {
        vehicle: key,
        title: card.dataset.title || info?.title || 'Phương tiện SmartMove',
        image: card.dataset.image || info?.image || cardImage?.getAttribute('src') || '',
        fallbackImage: info?.fallbackImage || '',
        summary: card.dataset.short || info?.summary || '',
        details: card.dataset.long || info?.details || 'Chưa có thông tin chi tiết.',
        spinFrames: info?.spinFrames || [],
        photoSource: info?.photoSource || '',
        photoSourceUrl: info?.photoSourceUrl || ''
    };
}

function setupVehiclePhotoSpin() {
    const viewer = document.getElementById('vehiclePhotoSpin');
    if (!viewer) return;

    const image = document.getElementById('modalImg');
    let pointerX = 0;
    let dragDistance = 0;

    viewer.addEventListener('pointerdown', (event) => {
        if (event.target.closest('button, a')) return;
        activePhotoSpin.dragging = true;
        pointerX = event.clientX;
        dragDistance = 0;
        viewer.setPointerCapture(event.pointerId);
    });

    viewer.addEventListener('pointermove', (event) => {
        if (!activePhotoSpin?.dragging) return;
        dragDistance += event.clientX - pointerX;
        pointerX = event.clientX;

        while (dragDistance <= -42) {
            advancePhotoFrame(1);
            dragDistance += 42;
        }
        while (dragDistance >= 42) {
            advancePhotoFrame(-1);
            dragDistance -= 42;
        }
    });

    const stopDragging = () => {
        if (activePhotoSpin) activePhotoSpin.dragging = false;
    };
    viewer.addEventListener('pointerup', stopDragging);
    viewer.addEventListener('pointercancel', stopDragging);

    viewer.addEventListener('keydown', (event) => {
        if (event.key === 'ArrowRight') {
            event.preventDefault();
            advancePhotoFrame(1);
        } else if (event.key === 'ArrowLeft') {
            event.preventDefault();
            advancePhotoFrame(-1);
        }
    });

    viewer.querySelector('[data-viewer-step="-1"]')?.addEventListener('click', () => advancePhotoFrame(-1));
    viewer.querySelector('[data-viewer-step="1"]')?.addEventListener('click', () => advancePhotoFrame(1));
    viewer.querySelector('[data-viewer-reset]')?.addEventListener('click', () => showPhotoFrame(0));

    image?.addEventListener('error', () => {
        const fallback = activePhotoSpin?.fallbackImage;
        if (fallback && image.src !== fallback) {
            image.src = fallback;
            document.getElementById('photoFrameCount').textContent = 'Ảnh dự phòng';
        }
    });
}

function renderVehiclePhotoSpin(info) {
    const image = document.getElementById('modalImg');
    const counter = document.getElementById('photoFrameCount');
    const sourceLink = document.getElementById('photoCredit');
    if (!image || !counter || !sourceLink) return;

    const frames = info.spinFrames.length ? info.spinFrames : [{ src: info.image, angle: info.title }];
    activePhotoSpin = { frames, index: 0, dragging: false, fallbackImage: info.fallbackImage };

    if (info.photoSourceUrl) {
        sourceLink.href = info.photoSourceUrl;
        sourceLink.textContent = `Ảnh: ${info.photoSource}`;
        sourceLink.hidden = false;
    } else {
        sourceLink.hidden = true;
    }

    frames.forEach((frame) => {
        const preload = new Image();
        preload.src = frame.src;
    });
    showPhotoFrame(0);
}

function advancePhotoFrame(direction) {
    if (!activePhotoSpin?.frames.length) return;
    const total = activePhotoSpin.frames.length;
    showPhotoFrame((activePhotoSpin.index + direction + total) % total);
}

function showPhotoFrame(index) {
    if (!activePhotoSpin?.frames.length) return;
    activePhotoSpin.index = index;

    const image = document.getElementById('modalImg');
    const counter = document.getElementById('photoFrameCount');
    const frame = activePhotoSpin.frames[index];
    if (image) {
        image.src = frame.src;
        image.alt = `${frame.angle}, ảnh ${index + 1} trên ${activePhotoSpin.frames.length}`;
    }
    if (counter) counter.textContent = `${frame.angle} · ${index + 1}/${activePhotoSpin.frames.length}`;
}

