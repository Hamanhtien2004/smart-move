    function switchToRegister() {
        tabRegisterBtn?.classList.add('active');
        tabRegisterBtn?.setAttribute('aria-selected', 'true');
        tabLoginBtn?.classList.remove('active');
        tabLoginBtn?.setAttribute('aria-selected', 'false');

        if (registerPanel) registerPanel.hidden = false;
        if (loginPanel) loginPanel.hidden = true;

        clearErrors();
        document.getElementById('regFullname')?.focus();
    }

    function clearErrors() {
        if (loginStatus) {
            loginStatus.className = 'auth-status';
            loginStatus.textContent = '';
        }
        if (registerStatus) {
            registerStatus.className = 'auth-status';
            registerStatus.textContent = '';
        }
        document.querySelectorAll('.auth-error-msg').forEach((el) => {
            el.textContent = '';
        });
    }

    tabLoginBtn?.addEventListener('click', switchToLogin);
    tabRegisterBtn?.addEventListener('click', switchToRegister);
    toRegisterLink?.addEventListener('click', (e) => {
        e.preventDefault();
        switchToRegister();
    });
    toLoginLink?.addEventListener('click', (e) => {
        e.preventDefault();
        switchToLogin();
    });

    document.getElementById('openLoginModal')?.addEventListener('click', () => {
        openModal(modal);
        switchToLogin();
    });

    document.getElementById('closeLoginModal')?.addEventListener('click', () => {
        closeModal('loginModal');
    });

    modal.addEventListener('click', (event) => {
        if (event.target === modal) closeModal('loginModal');
    });

